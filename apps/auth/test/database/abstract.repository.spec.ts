// Bogus executor: assigning it as `transaction` forces any query builder
// call to throw immediately (not a function), the Drizzle-side equivalent
// of the old "pass an invalid Sequelize option to force a runtime error"
// trick used throughout this suite.
const brokenTransaction = {} as unknown as DrizzleTx;

// updateByQuery looks the row up (select) before updating it — this variant
// only breaks the update half, so the exception surfaces from the update
// step specifically, not the lookup.
const brokenUpdateExecutor = (db: DrizzleDb): DrizzleTx =>
  ({
    select: (...args: Parameters<DrizzleDb['select']>) => db.select(...args),
    update: () => {
      throw new Error('broken transaction');
    },
  }) as unknown as DrizzleTx;

